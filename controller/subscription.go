func AdminListSubscriptionPlans(c *gin.Context) {
	var plans []model.SubscriptionPlan
	// Creation order, so the console's sequence column reads 1, 2, 3 from top to
	// bottom and a newly created plan always takes the next number.
	if err := model.DB.Order("id asc").Find(&plans).Error; err != nil {
		common.ApiError(c, err)
		return
	}
	if err := model.AttachSubscriptionPlanSeq(model.DB, plans); err != nil {
		common.SysError("failed to attach subscription plan seq: " + err.Error())
		c.JSON(http.StatusOK, gin.H{"success": false, "message": "获取订阅套餐列表失败，请稍后重试"})
		return
	}
	result := make([]SubscriptionPlanDTO, 0, len(plans))
	for _, p := range plans {
		p.NormalizeDefaults()
		result = append(result, SubscriptionPlanDTO{
			Plan: p,
		})
	}
	common.ApiSuccess(c, result)
}

