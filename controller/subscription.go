// normalizeAndValidateUpgradeGroup canonicalizes a plan's upgrade_group value
// (a comma-separated set of groups, empty = none) and reports whether every
// listed group exists. It returns the canonical value to store.
func normalizeAndValidateUpgradeGroup(value string) (string, bool) {
	normalized := model.NormalizeSubscriptionGroups(value)
	groupRatio := ratio_setting.GetGroupRatioCopy()
	for _, group := range strings.Split(normalized, ",") {
		if group == "" {
			continue
		}
		if _, ok := groupRatio[group]; !ok {
			return normalized, false
		}
	}
	return normalized, true
}

